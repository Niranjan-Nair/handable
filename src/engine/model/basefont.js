/*
 * Base skeleton font: the "pretrained" prior for handwrite.
 *
 * Single-stroke skeletons for printable ASCII, drawn the way people commonly
 * write print-script letters (stroke order and direction matter). Each stroke is
 * made of named-by-position segments (a bowl, a stem, an arch...). The engine
 * aligns your writing to these segments, learns what each of *your* segments
 * looks like, and reassembles them into characters you never wrote.
 *
 * Coordinates: baseline y = 0, x-height y = -0.5, ascender / cap line y = -1,
 * descender y = +0.45. y grows downward. x starts near 0.
 *
 * Output: glyphs[ch] = [stroke, ...], stroke = [segment, ...],
 *         segment = [[x, y], ...] (densified polyline).
 */
const D2R = Math.PI / 180;

// -- segment builders (each returns an array of segments) --------------------
function densifyLine(a, b, step = 0.02) {
  const n = Math.max(2, Math.ceil(Math.hypot(b[0] - a[0], b[1] - a[1]) / step) + 1);
  return Array.from({ length: n }, (_, i) => [
    a[0] + ((b[0] - a[0]) * i) / (n - 1),
    a[1] + ((b[1] - a[1]) * i) / (n - 1),
  ]);
}
// polyline: one segment per straight piece
const L = (...pts) => pts.slice(1).map((p, i) => densifyLine(pts[i], p));
// elliptical arc, angles in degrees, y-down (0 = right, 90 = down, -90 = up).
// Increasing angle = clockwise on screen.
const arc = (cx, cy, rx, ry, a0, a1) => {
  const n = Math.max(3, Math.ceil(Math.abs(a1 - a0) / 6) + 1);
  return [
    Array.from({ length: n }, (_, i) => {
      const t = (a0 + ((a1 - a0) * i) / (n - 1)) * D2R;
      return [cx + rx * Math.cos(t), cy + ry * Math.sin(t)];
    }),
  ];
};
// smooth Catmull-Rom curve through points (one segment)
const curve = (...pts) => {
  const out = [];
  for (let i = 0; i < pts.length - 1; i++) {
    const p0 = pts[i - 1] || pts[i];
    const p1 = pts[i];
    const p2 = pts[i + 1];
    const p3 = pts[i + 2] || p2;
    for (let k = 0; k < 10; k++) {
      const t = k / 10;
      const t2 = t * t;
      const t3 = t2 * t;
      const f = (a, b, c, d) =>
        0.5 * (2 * b + (-a + c) * t + (2 * a - 5 * b + 4 * c - d) * t2 + (-a + 3 * b - 3 * c + d) * t3);
      out.push([f(p0[0], p1[0], p2[0], p3[0]), f(p0[1], p1[1], p2[1], p3[1])]);
    }
  }
  out.push(pts[pts.length - 1].slice());
  return [out];
};
const dot = (x, y) => [[[x, y]]];

// stroke: concatenates segment groups; inserts a connecting line where the pen
// would travel between them without lifting.
function S(...groups) {
  const segs = [];
  for (const g of groups)
    for (const seg of g) {
      const prev = segs[segs.length - 1];
      if (prev) {
        const e = prev[prev.length - 1];
        const s = seg[0];
        if (Math.hypot(e[0] - s[0], e[1] - s[1]) > 0.015) segs.push(densifyLine(e, s));
      }
      segs.push(seg);
    }
  return segs;
}

